/* =========================================================
   회귀 실험실 — 데이터와 계산 (7차시)

   ⚠ 이 파일에는 화면(DOM) 코드가 하나도 없다.
      그래서 브라우저와 Node 에서 똑같이 돌아가고,
      tools/검사/verify_regress.cjs 가 이 파일을 그대로 불러
      화면에 나오는 숫자를 검사할 수 있다.
      ⇒ 계산을 여기 말고 js/regress.js 에 적지 말 것.

   ⚠ 데이터는 «씨앗 번호» 로 만든다 — 같은 씨앗 = 늘 같은 300개 점.
      Math.random 을 쓰면 새로 고칠 때마다 숫자가 달라져서
      학습지 정답과 화면이 어긋난다. (data-convert 에서 실제로 겪은 일)
   ========================================================= */
(function (전역) {
  "use strict";

  /* ---------------------------------------------------------
     0. 우리 학교의 «참 규칙» — 데이터를 만든 공식
     ---------------------------------------------------------
     학생에게는 알려 주지 않는다. AI 가 이것을 찾아내야 한다.
     PPT 의 계산표 `(학교 운영중 × 2.6) + (냉난방 필요도 × 0.1) + 0.2` 가
     바로 이 값이며, 4개 단서로 학습하면 실제로 이 값이 나온다
     (검사 스크립트가 매번 확인한다). */
  var 참규칙 = { 운영중: 2.6, 냉난방: 0.1, 기본: 0.2 };

  var 쾌적기온 = 18;          // 냉난방을 안 켜는 기온
  var 운영시작 = 8, 운영끝 = 17;   // 학교에 사람이 있는 시간

  /* 파생 단서(피처) 두 개 — 6차시에 표에 만들어 둔 열이다 */
  function 냉난방필요도(기온) { return Math.abs(기온 - 쾌적기온); }
  function 학교운영중(시각) { return (시각 >= 운영시작 && 시각 <= 운영끝) ? 1 : 0; }

  /* ---------------------------------------------------------
     1. 씨앗 난수 (mulberry32)
     --------------------------------------------------------- */
  function 난수만들기(씨앗) {
    var a = 씨앗 >>> 0;
    return function () {
      a = (a + 0x6D2B79F5) >>> 0;
      var t = a;
      t = Math.imul(t ^ (t >>> 15), t | 1);
      t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
      return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
  }
  /* 정규분포 잡음 (Box-Muller) — 실제 측정처럼 조금씩 흔들리게 */
  function 잡음(r) {
    var u = 1 - r(), v = r();
    return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v);
  }

  /* ---------------------------------------------------------
     2. 300개 기록 만들기 — 6차시에 합쳐 둔 그 표
     ---------------------------------------------------------
     기온 = 계절 곡선(1년) + 하루 곡선(낮이 더움) + 잡음
     ⚠ 계절 진폭·평균은 함부로 바꾸지 말 것.
        기온의 표본평균이 쾌적기온(18도)에서 멀어지면
        «단서 2개 모델» 이 우연히 정답 방향을 맞히게 되어
        이 수업의 결론(③④를 틀린다)이 무너진다.
        고쳤으면 tools/검사/verify_regress.cjs 를 반드시 다시 돌릴 것. */
  var 기본설정 = {
    개수: 300,
    씨앗: 20260821,
    연평균기온: 16,      // 계절 곡선의 가운데
    계절진폭: 14.5,      // 겨울 1.5도 ~ 여름 30.5도
    하루진폭: 5,         // 15시가 가장 더움
    기온잡음: 1.7,       // 이 값까지 합쳐 기온 범위가 -5 ~ 37도가 된다
                         // (시나리오의 33도·-5도가 데이터 «안» 에 있어야 외삽이 아니다)
    전력잡음: 0.25
  };

  function 데이터만들기(설정) {
    var s = {}, k;
    for (k in 기본설정) s[k] = 기본설정[k];
    if (설정) for (k in 설정) if (설정[k] != null) s[k] = 설정[k];

    var r = 난수만들기(s.씨앗), 표 = [], i;
    for (i = 0; i < s.개수; i++) {
      var 날 = 1 + Math.floor(r() * 365);
      var 시각 = Math.floor(r() * 24);

      var 그날평균 = s.연평균기온 - s.계절진폭 * Math.cos(2 * Math.PI * (날 - 20) / 365);
      var 기온 = 그날평균
               + s.하루진폭 * Math.cos(2 * Math.PI * (시각 - 15) / 24)
               + 잡음(r) * s.기온잡음;
      기온 = Math.round(기온 * 10) / 10;

      /* 습도는 «단서가 아니다» — 전력량과 아무 관계 없이 따로 뽑는다.
         일부러 이렇게 만들어 두어야 학생이 산점도에서 «관계 없음» 을 발견할 수 있다. */
      var 습도 = Math.round(40 + r() * 50);

      var 전력 = 참규칙.운영중 * 학교운영중(시각)
               + 참규칙.냉난방 * 냉난방필요도(기온)
               + 참규칙.기본
               + 잡음(r) * s.전력잡음;
      전력 = Math.round(Math.max(0.05, 전력) * 100) / 100;

      표.push({ 날: 날, 시각: 시각, 기온: 기온, 습도: 습도, 전력: 전력 });
    }
    return 표;
  }

  /* ---------------------------------------------------------
     3. 최소제곱법 — «오차가 가장 작은 직선» 을 한 번에 구한다
     ---------------------------------------------------------
     정규방정식을 가우스 소거로 푼다.
     화면의 «AI에게 맡기기» 는 이 답을 향해 조금씩 내려가는 모습을
     보여 주는 것이고, 도착점은 여기서 구한 값과 같다. */
  function 최소제곱(X, y) {
    var p = X[0].length, A = [], b = [], i, j, k;
    for (i = 0; i < p; i++) { A.push(new Array(p)); for (j = 0; j < p; j++) A[i][j] = 0; b.push(0); }
    for (k = 0; k < X.length; k++) {
      for (i = 0; i < p; i++) {
        b[i] += X[k][i] * y[k];
        for (j = 0; j < p; j++) A[i][j] += X[k][i] * X[k][j];
      }
    }
    for (i = 0; i < p; i++) {                       /* 앞으로 소거 (부분 피벗) */
      var m = i;
      for (k = i + 1; k < p; k++) if (Math.abs(A[k][i]) > Math.abs(A[m][i])) m = k;
      var tr = A[i]; A[i] = A[m]; A[m] = tr;
      var tb = b[i]; b[i] = b[m]; b[m] = tb;
      if (Math.abs(A[i][i]) < 1e-12) continue;      /* 쓸모없는 열은 계수 0 으로 둔다 */
      for (k = i + 1; k < p; k++) {
        var f = A[k][i] / A[i][i];
        for (j = i; j < p; j++) A[k][j] -= f * A[i][j];
        b[k] -= f * b[i];
      }
    }
    var w = new Array(p);
    for (i = p - 1; i >= 0; i--) {
      var s = b[i];
      for (j = i + 1; j < p; j++) s -= A[i][j] * w[j];
      w[i] = (Math.abs(A[i][i]) < 1e-12) ? 0 : s / A[i][i];
    }
    return w;
  }

  /* ---------------------------------------------------------
     4. 단서 묶음(모델) 정의
     ---------------------------------------------------------
     `뽑기` 는 기록 한 줄에서 단서 값을 꺼내는 함수다.
     맨 앞의 1 은 «기본값(편향)» 자리다. */
  var 단서표 = {
    시각:   { 이름: "시각",          뽑기: function (r) { return r.시각; } },
    기온:   { 이름: "기온",          뽑기: function (r) { return r.기온; } },
    습도:   { 이름: "습도",          뽑기: function (r) { return r.습도; } },
    냉난방: { 이름: "냉난방 필요도", 뽑기: function (r) { return 냉난방필요도(r.기온); } },
    운영중: { 이름: "학교 운영중",   뽑기: function (r) { return 학교운영중(r.시각); } }
  };

  /* 단서 이름 목록으로 모델 하나를 학습한다 */
  function 학습(표, 단서들) {
    var X = 표.map(function (r) {
      var row = [1];
      단서들.forEach(function (nm) { row.push(단서표[nm].뽑기(r)); });
      return row;
    });
    var y = 표.map(function (r) { return r.전력; });
    var w = 최소제곱(X, y);

    function 예측(r) {
      var v = w[0];
      단서들.forEach(function (nm, i) { v += w[i + 1] * 단서표[nm].뽑기(r); });
      return v;
    }
    return {
      단서들: 단서들.slice(),
      기본값: w[0],
      계수: w.slice(1),
      예측: 예측,
      오차합: 오차합(표, 예측),
      평균오차: 오차합(표, 예측) / 표.length
    };
  }

  /* 오차 합 = |실제 − 예측| 을 모두 더한 것.
     ⚠ 중1 이 이해할 수 있게 «거리를 더한다» 로 보여 준다.
        AI 가 속으로 줄이는 것은 제곱 오차이지만, 둘 다 같은 직선을 향한다. */
  function 오차합(표, 예측) {
    var s = 0;
    표.forEach(function (r) { s += Math.abs(r.전력 - 예측(r)); });
    return s;
  }

  /* 아무것도 안 배운 AI = 늘 평균만 대답하는 AI. 비교 기준선이다. */
  function 평균모델(표) {
    var m = 표.reduce(function (a, r) { return a + r.전력; }, 0) / 표.length;
    return { 평균: m, 예측: function () { return m; }, 오차합: 오차합(표, function () { return m; }) };
  }

  /* 단서 하나로 직선 하나 (탭 ②·④ 에서 쓴다) */
  function 직선맞추기(점들) {                     /* 점들 = [{x, y}, …] */
    var X = 점들.map(function (p) { return [1, p.x]; });
    var y = 점들.map(function (p) { return p.y; });
    var w = 최소제곱(X, y);
    return { 절편: w[0], 기울기: w[1] };
  }
  function 직선오차합(점들, 기울기, 절편) {
    var s = 0;
    점들.forEach(function (p) { s += Math.abs(p.y - (기울기 * p.x + 절편)); });
    return s;
  }

  /* ---------------------------------------------------------
     5. 시험 시나리오 네 가지 (PPT 와 같은 순서)
     ---------------------------------------------------------
     `실제` 는 손으로 적은 값이 아니라 «참 규칙» 으로 계산한 값이다.
     ⇒ 규칙을 고치면 시나리오 값도 저절로 따라간다. */
  var 시나리오 = [
    { 이름: "한여름 5교시",   시각: 14, 기온: 33, 설명: "교실마다 에어컨 · 사람 가득" },
    { 이름: "간절기 등교",     시각: 8,  기온: 18, 설명: "냉난방을 안 켜는 딱 좋은 날" },
    { 이름: "한밤중 열대야",   시각: 22, 기온: 33, 설명: "더운데 학교가 텅 비었다" },
    { 이름: "한겨울 등교",     시각: 8,  기온: -5, 설명: "히터를 세게 켠다" }
  ];
  function 실제값(시각, 기온) {
    return 참규칙.운영중 * 학교운영중(시각)
         + 참규칙.냉난방 * 냉난방필요도(기온)
         + 참규칙.기본;
  }

  /* ---------------------------------------------------------
     6. 탭 ②③ 에서 쓰는 «여름철 수업 시간» 만 뽑은 작은 표
     ---------------------------------------------------------
     학교 운영중(=1) 이고 기온이 쾌적기온보다 높은 기록만 모으면
     참 규칙이 깔끔한 직선 하나가 된다 :
        전력 = 0.1 × 기온 + 1.0
     (2.6 + 0.1×(기온−18) + 0.2 = 0.1×기온 + 1.0)
     그래서 33도를 읽으면 4.3kWh — PPT 시나리오 ① 과 같은 값이다. */
  var 여름직선 = { 기울기: 참규칙.냉난방, 절편: 참규칙.운영중 + 참규칙.기본 - 참규칙.냉난방 * 쾌적기온 };

  function 여름수업표(표) {
    return 표.filter(function (r) { return 학교운영중(r.시각) === 1 && r.기온 >= 쾌적기온; });
  }

  /* ---------------------------------------------------------
     7. «기온 하나만» 아는 AI  ← PPT 의 시험 결과가 바로 이것이다
     ---------------------------------------------------------
     6차시에서 «더우면 에어컨 → 전기 많이» 를 확인했고,
     탭 ② 에서 여름철 수업 시간 기록으로 직선을 그으면 `0.1×기온 + 1.0` 이 나온다.
     그 직선을 **모든 시각 · 모든 계절에 그대로** 쓰는 것이 «기온만 아는 AI» 다.

     네 시나리오에 넣으면 PPT 와 같은 결과가 나온다 :
       ① 14시 33도 → 4.3  (실제 4.3) ○ 맞힌다
       ② 8시  18도 → 2.8  (실제 2.8) ○ 맞힌다
       ③ 22시 33도 → 4.3  (실제 1.7) ✘ «많이 쓴다» 고 한다  ← PPT 4.1
       ④ 8시  −5도 → 0.5  (실제 5.1) ✘ «적게 쓴다» 고 한다  ← PPT 1.2
     ⇒ «시간을 안 보기» 때문에 ③ 을 틀리고, «기온이 U자» 이기 때문에 ④ 를 틀린다.

     ⚠ 300개 전체를 기온 하나로 최소제곱하면 기울기가 0.011 로 거의 평평해진다
        (|기온−18| 이 접혀 있어서 그렇다). 그것은 «아무것도 못 배운 직선» 이라
        수업에서 보여 줄 것이 없다. 그래서 **학생이 탭 ② 에서 직접 맞춘 직선**을 쓴다 —
        학생이 자기 손으로 만든 규칙이 어디서 무너지는지 보는 것이 이 수업의 장면이다. */
  function 기온모델(표) {
    var 여름 = 여름수업표(표);
    var L = 직선맞추기(여름.map(function (r) { return { x: r.기온, y: r.전력 }; }));
    function 예측(r) { return L.기울기 * r.기온 + L.절편; }
    return {
      이름: "기온만", 기울기: L.기울기, 절편: L.절편,
      예측: 예측,
      오차합: 오차합(표, 예측),
      평균오차: 오차합(표, 예측) / 표.length
    };
  }

  전역.RegModel = {
    참규칙: 참규칙, 쾌적기온: 쾌적기온, 운영시작: 운영시작, 운영끝: 운영끝,
    기본설정: 기본설정, 여름직선: 여름직선,
    냉난방필요도: 냉난방필요도, 학교운영중: 학교운영중,
    난수만들기: 난수만들기,
    데이터만들기: 데이터만들기, 여름수업표: 여름수업표, 기온모델: 기온모델,
    단서표: 단서표, 학습: 학습, 평균모델: 평균모델,
    오차합: 오차합, 최소제곱: 최소제곱,
    직선맞추기: 직선맞추기, 직선오차합: 직선오차합,
    시나리오: 시나리오, 실제값: 실제값
  };
  if (typeof module !== "undefined" && module.exports) module.exports = 전역.RegModel;
})(typeof window !== "undefined" ? window : globalThis);
