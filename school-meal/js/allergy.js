/**
 * 알레르기 유발 식품 표시 — 번호를 이름으로 풀어 준다.
 *
 * NEIS 가 주는 식단은 이렇게 생겼다 :
 *     건새우아욱국 (5.6.9)
 * 여기서 (5.6.9) 는 «대두·밀·새우» 라는 뜻이다.
 * 번호만 있으면 아무도 못 읽으므로 이름으로 바꿔 보여 준다.
 *
 * 식품의약품안전처가 정한 «알레르기 유발물질 표시 대상» 19가지다.
 * 학교마다 18가지(잣 제외)만 쓰기도 하고, 드물게 모르는 번호가 섞이기도 한다.
 * 그때는 번호를 그대로 보여 준다 — 조용히 지우면 알레르기 있는 학생이 위험하다.
 */

(function (전역) {
  "use strict";

  var 이름표 = {
    1: "난류",
    2: "우유",
    3: "메밀",
    4: "땅콩",
    5: "대두",
    6: "밀",
    7: "고등어",
    8: "게",
    9: "새우",
    10: "돼지고기",
    11: "복숭아",
    12: "토마토",
    13: "아황산류",
    14: "호두",
    15: "닭고기",
    16: "쇠고기",
    17: "오징어",
    18: "조개류",
    19: "잣",
  };

  /**
   * 메뉴 한 줄에서 알레르기 번호를 떼어 낸다.
   *   "건새우아욱국 (5.6.9)"        → { 이름:"건새우아욱국", 번호:[5,6,9] }
   *   "쇠고기(국내산)미역국"        → { 이름:"쇠고기(국내산)미역국", 번호:[] }
   *   "친환경통밀밥 (6)"            → { 이름:"친환경통밀밥", 번호:[6] }
   *
   * 🔴 «맨 끝의, 숫자와 점만 든 괄호» 만 알레르기로 본다.
   *    메뉴 이름 안에도 괄호가 들어가므로(원산지 표기 등) 아무 괄호나 떼면
   *    «쇠고기» 만 남고 «(국내산)» 이 알레르기로 둔갑한다.
   */
  function 가르기(줄) {
    var 글 = String(줄 == null ? "" : 줄).replace(/\s+/g, " ").trim();
    var 맞음 = 글.match(/^(.*?)\s*\(([\d.\s]+)\)$/);
    if (!맞음) return { 이름: 글, 번호: [] };

    var 번호 = 맞음[2]
      .split(/[.\s]+/)
      .map(function (n) { return parseInt(n, 10); })
      .filter(function (n) { return !isNaN(n) && n > 0; });

    // 중복을 없애고 번호 순으로 — "(6.6.5)" 같은 자료가 실제로 있다.
    var 본것 = {};
    번호 = 번호.filter(function (n) {
      if (본것[n]) return false;
      본것[n] = true;
      return true;
    }).sort(function (a, b) { return a - b; });

    var 이름 = 맞음[1].trim();
    // 괄호를 떼고 나니 이름이 없어졌다면 원래 줄이 맞다(예: "(5.6)" 만 있는 자료).
    return { 이름: 이름 || 글, 번호: 번호 };
  }

  /** 번호 하나 → 이름. 모르는 번호는 "17번" 처럼 번호 그대로. */
  function 이름(번호) {
    return 이름표[번호] || (번호 + "번");
  }

  /** 번호 여럿 → "대두 · 밀 · 새우" */
  function 이름들(번호들) {
    if (!번호들 || !번호들.length) return "";
    return 번호들.map(이름).join(" · ");
  }

  /**
   * 메뉴 여러 줄에 든 알레르기 번호를 하나로 모은다(그 날 전체 알레르기).
   * 화면에서 «오늘 급식의 알레르기» 한 줄을 만들 때 쓴다.
   */
  function 모으기(메뉴들) {
    var 본것 = {};
    var 모음 = [];
    (메뉴들 || []).forEach(function (m) {
      (m.번호 || []).forEach(function (n) {
        if (!본것[n]) { 본것[n] = true; 모음.push(n); }
      });
    });
    return 모음.sort(function (a, b) { return a - b; });
  }

  전역.Allergy = {
    이름표: 이름표,
    가르기: 가르기,
    이름: 이름,
    이름들: 이름들,
    모으기: 모으기,
  };
})(typeof window !== "undefined" ? window : globalThis);

// 검사 파일(node)에서도 쓸 수 있게 한다.
if (typeof module !== "undefined" && module.exports) {
  module.exports = (typeof window !== "undefined" ? window : globalThis).Allergy;
}
