/**
 * stat.js — 과거 기상 자료로 «그 날짜가 어떤 날이었나» 를 세는 곳
 *
 * 🔴 이 파일은 화면(DOM)을 쓰지 않는다.
 *    브라우저 없이 node 로 불러 검사할 수 있어야 하기 때문이다.
 *    tools/검사/verify_stat.cjs 가 이 파일을 그대로 읽어 돌린다.
 *
 * 🚨 이 앱에서 가장 조용히 틀리기 쉬운 자리다.
 *    숫자가 그럴싸하게 나오고 오류는 나지 않는다. 그리고 그 숫자를 보고
 *    운동회 날짜를 정한다. 아래 네 가지를 절대 무너뜨리지 말 것 :
 *
 *    ① 결측(자료 없음)을 0 으로 읽지 않는다.
 *       「그날 비 0mm」 가 되어 강수확률이 조용히 낮아진다.
 *       결측은 «표본에서 뺀다» — 그래서 항목마다 표본 수가 다르다.
 *    ② 표본 수를 언제나 함께 돌려준다.
 *       「27%」 가 아니라 「자료가 있는 28년 중 8번」 이라야 사람이 판단할 수 있다.
 *    ③ 연속 구간(2박3일)은 «실제 그 구간» 을 센다.
 *       날씨는 하루하루가 독립이 아니다(비 온 다음날 비 올 확률이 높다).
 *       하루 확률을 곱하면 실제보다 «낮게» 나온다.
 *    ④ 구간 안에 결측이 하나라도 있으면 그 해는 통째로 뺀다.
 *       「사흘 내내 맑았나」 를 반쪽 자료로 판단할 수 없다.
 */

(function (뿌리) {
  "use strict";

  // ── 자료 푸는 곳 ───────────────────────────────────────────────
  // data/<지점>.js 가 담고 있는 생김새 :
  //   { 지점, 이름, 위도, 경도, 시작, 끝, 칸[], 배수[], 해: { 1996: "...", ... } }
  // 한 해는 «하루씩 ; 로 이은 한 줄» 이고, 하루는 «칸을 , 로 이은 것» 이다.
  // 결측은 빈칸으로 둔다 — 0 이 아니다.
  //   "12,-15,68,,21,45,72,89"  ← 네 번째(강수량)가 결측

  var 칸이름 = ["평균기온", "최저기온", "최고기온", "강수량",
                "평균풍속", "최대순간풍속", "습도", "일조"];

  /** 한 해 줄 → [[값,...], ...] · 결측은 null */
  function 해풀기(줄, 배수) {
    var 날들 = String(줄).split(";");
    var 나온다 = new Array(날들.length);
    for (var i = 0; i < 날들.length; i++) {
      var 칸 = 날들[i].split(",");
      var 하루 = new Array(배수.length);
      for (var k = 0; k < 배수.length; k++) {
        var 글 = 칸[k];
        // 🔴 빈칸·undefined 는 결측이다. Number("") 은 0 이 되므로 먼저 걸러야 한다.
        if (글 === undefined || 글 === "" || 글 === null) { 하루[k] = null; continue; }
        var 수 = Number(글);
        하루[k] = isFinite(수) ? 수 / 배수[k] : null;
      }
      나온다[i] = 하루;
    }
    return 나온다;
  }

  /** 원자료 → 다루기 쉬운 표. 한 번만 하고 결과를 자료에 붙여 둔다. */
  function 풀기(자료) {
    if (!자료 || !자료.해) throw new Error("자료가 비었습니다");
    if (자료.__표) return 자료.__표;                 // 이미 푼 것을 다시 쓴다

    var 배수 = 자료.배수 || [10, 10, 10, 10, 10, 10, 1, 10];
    var 표 = {};
    for (var 해 in 자료.해) {
      if (!Object.prototype.hasOwnProperty.call(자료.해, 해)) continue;
      표[Number(해)] = 해풀기(자료.해[해], 배수);
    }

    var 것 = {
      지점: 자료.지점, 이름: 자료.이름,
      위도: 자료.위도, 경도: 자료.경도,
      시작: Number(자료.시작), 끝: Number(자료.끝),
      칸: 자료.칸 || 칸이름,
      해: 표,
      가짜: !!자료.가짜                              // 검사용 가짜 자료 표시
    };
    try { Object.defineProperty(자료, "__표", { value: 것, enumerable: false }); }
    catch (e) { 자료.__표 = 것; }
    return 것;
  }

  // ── 날짜 셈 ──────────────────────────────────────────────────
  var 하루 = 86400000;

  /** 그 해 1월 1일부터 며칠째인가 (0부터) */
  function 몇째날(해, 월, 일) {
    return Math.round((Date.UTC(해, 월 - 1, 일) - Date.UTC(해, 0, 1)) / 하루);
  }

  /** 그 해의 날 수 */
  function 해길이(해) {
    return Math.round((Date.UTC(해 + 1, 0, 1) - Date.UTC(해, 0, 1)) / 하루);
  }

  /**
   * 한 날을 집는다. 없으면 null.
   * ⚠ 2월 29일을 평년에 물으면 Date 가 3월 1일로 넘긴다 — 그대로 받아들인다.
   *   윤일에 하는 행사는 드물고, 이월이 «가장 가까운 날» 이라 뜻이 통한다.
   */
  function 집기(표, 해, 월, 일) {
    var 때 = Date.UTC(해, 월 - 1, 일);
    var 진짜해 = new Date(때).getUTCFullYear();
    var 줄 = 표.해[진짜해];
    if (!줄) return null;
    var i = Math.round((때 - Date.UTC(진짜해, 0, 1)) / 하루);
    if (i < 0 || i >= 줄.length) return null;
    return { 해: 진짜해, 때: 때, 값: 줄[i] };
  }

  // ── ① 날짜 창의 표본 모으기 ───────────────────────────────────
  /**
   * (월, 일) 을 가운데 두고 앞뒤 «폭» 일까지 긁어 모은다.
   *
   * 왜 폭을 두나 : 그날 하루만 보면 표본이 30개뿐이라 들쭉날쭉하다.
   *   ±3일이면 30년 × 7일 = 210 표본이 되어 훨씬 안정적이다.
   * ⚠ 다만 «비 올 확률» 을 물을 때는 이것이 «그 무렵 하루가 비일 확률» 이지
   *   «그 날짜가 비일 확률» 이 아니다. 화면에 그렇게 적어야 한다.
   */
  function 창(표, 뜻) {
    var 월 = 뜻.월, 일 = 뜻.일;
    var 폭 = 뜻.폭 == null ? 3 : 뜻.폭;
    var 부터 = 뜻.부터 == null ? 표.시작 : 뜻.부터;
    var 까지 = 뜻.까지 == null ? 표.끝 : 뜻.까지;

    var 모음 = [];
    for (var 해 = 부터; 해 <= 까지; 해++) {
      var 가운데 = Date.UTC(해, 월 - 1, 일);
      for (var d = -폭; d <= 폭; d++) {
        var 때 = 가운데 + d * 하루;
        var 그 = new Date(때);
        var 것 = 집기(표, 그.getUTCFullYear(), 그.getUTCMonth() + 1, 그.getUTCDate());
        if (것) 모음.push(것);
      }
    }
    return 모음;
  }

  // ── ② 표본 → 요약 ────────────────────────────────────────────
  var 칸번호 = { 평균기온: 0, 최저기온: 1, 최고기온: 2, 강수량: 3,
                 평균풍속: 4, 최대순간풍속: 5, 습도: 6, 일조: 7 };

  /**
   * 「몇 번 넘었나」 를 센다.
   * 🔴 결측인 날은 «셈» 에도 «표본» 에도 넣지 않는다.
   *    그래야 「자료가 있는 28일 중 8일」 이 나온다.
   */
  function 넘은수(표본, 칸, 금, 위로) {
    var k = 칸번호[칸];
    var 셈 = 0, 표 = 0;
    for (var i = 0; i < 표본.length; i++) {
      var v = 표본[i].값[k];
      if (v === null || v === undefined) continue;   // ← ① 결측을 0 으로 읽지 않는다
      표++;
      if (위로 === false ? v <= 금 : v >= 금) 셈++;
    }
    return { 셈: 셈, 표본: 표, 비율: 표 ? 셈 / 표 : null };
  }

  /** 평균·최소·최대. 결측은 빼고 센다. */
  function 값재기(표본, 칸) {
    var k = 칸번호[칸];
    var 합 = 0, 표 = 0, 작 = Infinity, 큰 = -Infinity;
    for (var i = 0; i < 표본.length; i++) {
      var v = 표본[i].값[k];
      if (v === null || v === undefined) continue;
      합 += v; 표++;
      if (v < 작) 작 = v;
      if (v > 큰) 큰 = v;
    }
    if (!표) return { 평균: null, 최소: null, 최대: null, 표본: 0 };
    return { 평균: 합 / 표, 최소: 작, 최대: 큰, 표본: 표 };
  }

  /** 기준값 — 화면에서 바꿀 수 있다. 여기 값은 «그냥 기본» 이다. */
  var 기본기준 = {
    비: 1,          // 일강수량 이 값 이상이면 «비 온 날» (기상청 강수일 기준)
    큰비: 20,       // 행사를 접어야 하는 수준
    더위: 33,       // 최고기온 — 폭염주의보 기준
    더위약: 31,     // 야외 체육활동을 줄이라는 수준
    추위: 0,        // 최저기온 이 값 이하
    강풍: 14        // 최대순간풍속 m/s — 천막·현수막이 위험해지는 수준
  };

  /**
   * 표본 한 무더기를 요약한다.
   * 🔴 모든 항목이 «표본 수» 를 함께 들고 나간다(②). 화면은 그것을 반드시 보여 준다.
   */
  function 요약(표본, 기준) {
    var 금 = {};
    for (var 키 in 기본기준) 금[키] = (기준 && 기준[키] != null) ? 기준[키] : 기본기준[키];

    return {
      날수: 표본.length,
      기준: 금,
      비:    넘은수(표본, "강수량", 금.비),
      큰비:  넘은수(표본, "강수량", 금.큰비),
      더위:  넘은수(표본, "최고기온", 금.더위),
      더위약: 넘은수(표본, "최고기온", 금.더위약),
      추위:  넘은수(표본, "최저기온", 금.추위, false),
      강풍:  넘은수(표본, "최대순간풍속", 금.강풍),
      최고:  값재기(표본, "최고기온"),
      최저:  값재기(표본, "최저기온"),
      강수:  값재기(표본, "강수량"),
      바람:  값재기(표본, "평균풍속")
    };
  }

  // ── ③ 연속 구간 (1박2일·2박3일) ──────────────────────────────
  /**
   * 🔴 「사흘 중 하루라도 비」 를 하루 확률의 곱으로 내면 «틀린다».
   *    날씨에는 자기상관이 있어 실제보다 낮게 나온다.
   *    그래서 해마다 «실제 그 사흘» 을 들여다보고 센다.
   *
   * ④ 구간 안에 결측이 하나라도 있으면 그 해는 통째로 뺀다.
   *   반쪽 자료로 「사흘 내내 맑았다」 를 말할 수 없기 때문이다.
   */
  function 구간(표, 뜻) {
    var 월 = 뜻.월, 일 = 뜻.일;
    var 일수 = Math.max(1, 뜻.일수 || 1);
    var 부터 = 뜻.부터 == null ? 표.시작 : 뜻.부터;
    var 까지 = 뜻.까지 == null ? 표.끝 : 뜻.까지;
    var 금 = {};
    for (var 키 in 기본기준) 금[키] = (뜻.기준 && 뜻.기준[키] != null) ? 뜻.기준[키] : 기본기준[키];

    var 해마다 = [];
    for (var 해 = 부터; 해 <= 까지; 해++) {
      var 처음 = Date.UTC(해, 월 - 1, 일);
      var 날들 = [], 온전 = true;
      for (var d = 0; d < 일수; d++) {
        var 그 = new Date(처음 + d * 하루);
        var 것 = 집기(표, 그.getUTCFullYear(), 그.getUTCMonth() + 1, 그.getUTCDate());
        // 강수·최저·최고 셋 중 하나라도 없으면 이 해는 판단할 수 없다
        if (!것 || 것.값[3] === null || 것.값[1] === null || 것.값[2] === null) {
          온전 = false; break;
        }
        날들.push(것);
      }
      if (!온전) { 해마다.push({ 해: 해, 온전: false }); continue; }

      var 비온날 = 0, 총강수 = 0, 최대일강수 = 0;
      var 가장낮은 = Infinity, 가장높은 = -Infinity, 큰비있나 = false;
      for (var i = 0; i < 날들.length; i++) {
        var v = 날들[i].값;
        총강수 += v[3];
        if (v[3] >= 금.비) 비온날++;
        if (v[3] >= 금.큰비) 큰비있나 = true;
        if (v[3] > 최대일강수) 최대일강수 = v[3];
        if (v[1] < 가장낮은) 가장낮은 = v[1];
        if (v[2] > 가장높은) 가장높은 = v[2];
      }
      해마다.push({
        해: 해, 온전: true, 비온날: 비온날, 총강수: 총강수,
        최대일강수: 최대일강수, 최저기온: 가장낮은, 최고기온: 가장높은,
        큰비: 큰비있나, 내내맑음: 비온날 === 0
      });
    }

    var 쓸것 = 해마다.filter(function (a) { return a.온전; });
    var 표본 = 쓸것.length;
    function 세기(고르개) {
      var n = 0;
      for (var i = 0; i < 쓸것.length; i++) if (고르개(쓸것[i])) n++;
      return { 셈: n, 표본: 표본, 비율: 표본 ? n / 표본 : null };
    }
    function 평균(뽑개) {
      if (!표본) return null;
      var 합 = 0;
      for (var i = 0; i < 쓸것.length; i++) 합 += 뽑개(쓸것[i]);
      return 합 / 표본;
    }

    return {
      일수: 일수, 기준: 금, 해마다: 해마다, 표본: 표본,
      뺀해: 해마다.length - 표본,
      내내맑음: 세기(function (a) { return a.내내맑음; }),
      하루라도비: 세기(function (a) { return a.비온날 > 0; }),
      이틀이상비: 세기(function (a) { return a.비온날 >= 2; }),
      큰비: 세기(function (a) { return a.큰비; }),
      평균비온날: 평균(function (a) { return a.비온날; }),
      평균최저: 평균(function (a) { return a.최저기온; }),
      평균최고: 평균(function (a) { return a.최고기온; })
    };
  }

  // ── ④ 최근 N년만 따로 보기 (기후변화 대비) ───────────────────
  /**
   * 🔴 30년 평균은 지금보다 서늘하다. 그것만 보여 주면 9~10월 기온을 과소평가한다.
   *    그래서 «30년» 과 «최근 10년» 을 나란히 낸다. 앱은 둘 다 보여 주고
   *    어느 쪽이 옳다고 말하지 않는다 — 다른 것을 보는 것이 판단에 도움이 된다.
   */
  function 견주기(표, 뜻) {
    var 최근 = 뜻.최근 || 10;
    var 온통 = 요약(창(표, 뜻), 뜻.기준);
    var 요새뜻 = {};
    for (var 키 in 뜻) 요새뜻[키] = 뜻[키];
    요새뜻.부터 = Math.max(표.시작, 표.끝 - 최근 + 1);
    var 요새 = 요약(창(표, 요새뜻), 뜻.기준);
    return {
      온통: 온통, 요새: 요새,
      온통기간: [뜻.부터 == null ? 표.시작 : 뜻.부터, 뜻.까지 == null ? 표.끝 : 뜻.까지],
      요새기간: [요새뜻.부터, 표.끝]
    };
  }

  뿌리.Stat = {
    풀기: 풀기, 창: 창, 요약: 요약, 구간: 구간, 견주기: 견주기,
    집기: 집기, 몇째날: 몇째날, 해길이: 해길이,
    칸이름: 칸이름, 칸번호: 칸번호, 기본기준: 기본기준
  };
})(typeof window !== "undefined" ? window : (typeof globalThis !== "undefined" ? globalThis : this));

// node 에서 검사할 때 쓴다 (브라우저에서는 module 이 없어 그냥 넘어간다)
if (typeof module !== "undefined" && module.exports) {
  module.exports = (typeof globalThis !== "undefined" ? globalThis : this).Stat;
}
