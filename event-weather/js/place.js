/**
 * place.js — 「어디를 볼 것인가」 를 정하는 곳
 *
 * 🔴 세 겹으로 두고, **아래로 갈수록 아무것도 없어도 된다.**
 *
 *   ① 학교 이름으로 찾기   「거제중」 → 거제시 → 가장 가까운 관측소
 *      └ schools/<시도코드>.js 가 있어야 한다. 없으면 이 칸은 저절로 숨는다.
 *   ② 시·도 → 관측지점 고르기                    ← 🔴 이것이 바탕이다
 *      └ data/지점.js 만 있으면 언제나 된다.
 *   ③ 지점 번호를 아는 사람이 바로 고르기
 *
 *   ①이 편하지만 ②③ 이 없으면 학교 목록을 못 만든 사람은 앱을 아예 못 쓴다.
 *   폴더만 복사해 간 사람, NEIS 인증키가 없는 사람이 그렇다.
 *   그래서 **①은 편의이고 ②가 바탕**이다. 이 순서를 뒤집지 말 것.
 *
 * ── 시군구 → 어느 관측소를 볼까 ──────────────────────────────
 *   ㉮ 시군구 이름이 같은 지점               (거제시 → 거제)
 *   ㉯ `data/격자.js` 가 있으면 **거리로** 고른다
 *   ㉰ 그것도 없으면 늘어놓고 «고르세요» 라고 묻는다
 *
 * 🔴 ㉯ 에서 재는 것은 «지점의 좌표» 가 아니라 **그 지점이 있는 시군구의 가운데**다.
 *    지점의 진짜 좌표를 아직 못 구했기 때문이다(지어내지 않았다).
 *    우리가 묻는 것이 결국 「어느 동네의 관측소를 볼까」 라서 뜻은 통하지만
 *    **몇 km 어긋난다** — 화면이 그렇게 말한다.
 *
 * 🚨 «골라야한다» 를 «저절로 골랐다» 로 바꾸지 말 것.
 *    아무 근거 없이 지점을 고르면 그 통계로 행사 날짜를 정하게 되는데,
 *    틀렸다는 것을 알아챌 방법이 없다.
 */

(function (뿌리) {
  "use strict";

  /* 시도교육청 코드 — school-meal/tools/학교목록_만들기.js 와 같은 표다.
     학교 목록 파일 이름이 이 코드다(`schools/S10.js`). */
  var 교육청 = [
    ["B10", "서울특별시"], ["C10", "부산광역시"], ["D10", "대구광역시"],
    ["E10", "인천광역시"], ["F10", "광주광역시"], ["G10", "대전광역시"],
    ["H10", "울산광역시"], ["I10", "세종특별자치시"], ["J10", "경기도"],
    ["K10", "강원특별자치도"], ["M10", "충청북도"], ["N10", "충청남도"],
    ["P10", "전북특별자치도"], ["Q10", "전라남도"], ["R10", "경상북도"],
    ["S10", "경상남도"], ["T10", "제주특별자치도"]
  ];

  var 학교담음 = {};      // 시도코드 → 배열 · null («없다» 도 기억한다)
  var 부르는중 = {};      // 시도코드 → Promise (겹쳐 부르지 않게)

  function 시도코드(시도이름) {
    for (var i = 0; i < 교육청.length; i++) {
      if (교육청[i][1] === 시도이름) return 교육청[i][0];
    }
    return null;
  }

  /* ── ② 바탕 : 지점 목록에서 시·도를 뽑는다 ─────────────── */
  function 시도들(지점목록) {
    var 본것 = {}, 나온다 = [];
    (지점목록 || []).forEach(function (s) {
      if (s.시도 && !본것[s.시도]) { 본것[s.시도] = 1; 나온다.push(s.시도); }
    });
    // 교육청 표의 차례를 따른다(가나다순보다 익숙하다)
    나온다.sort(function (a, b) {
      var ia = 교육청.findIndex(function (e) { return e[1] === a; });
      var ib = 교육청.findIndex(function (e) { return e[1] === b; });
      return (ia < 0 ? 99 : ia) - (ib < 0 ? 99 : ib);
    });
    return 나온다;
  }

  function 그시도지점(지점목록, 시도) {
    return (지점목록 || []).filter(function (s) { return s.시도 === 시도; });
  }

  /* ── ① 편의 : 학교 목록 부르기 ──────────────────────────
     data.js 와 같은 까닭으로 `.js` + <script> 다(file:// 에서 fetch 가 막힌다). */
  function 학교부르기(코드) {
    // 🔴 «없다» 도 기억한다. `if (학교담음[코드])` 로만 보면 null 이 거짓이라
    //    없는 파일을 **글자를 칠 때마다 다시 부른다**(404 가 줄줄이 찍혔다).
    if (Object.prototype.hasOwnProperty.call(학교담음, 코드)) {
      return Promise.resolve(학교담음[코드]);
    }
    if (부르는중[코드]) return 부르는중[코드];      // 겹쳐 부르는 것도 막는다

    var 열쇠 = "SCHOOLS_" + 코드;
    if (뿌리[열쇠]) { 학교담음[코드] = 뿌리[열쇠]; return Promise.resolve(학교담음[코드]); }

    var 일 = new Promise(function (되면) {
      var s = document.createElement("script");
      // data.js 와 같은 까닭으로 판 번호를 붙인다(브라우저가 옛 파일을 쓰지 않게)
      var 주소 = "schools/" + 코드 + ".js";
      s.src = 뿌리.앱판 ? 주소 + "?v=" + encodeURIComponent(뿌리.앱판) : 주소;
      s.async = true;
      s.onload = s.onerror = function () {
        s.remove();
        // ⚠ file:// 에서는 onerror 가 안 뜰 수 있으니 «값이 왔는가» 로 본다
        학교담음[코드] = 뿌리[열쇠] || null;
        delete 부르는중[코드];
        되면(학교담음[코드]);
      };
      document.head.appendChild(s);
    });
    부르는중[코드] = 일;
    return 일;
  }

  /** 학교 목록이 «맛보기(일부만)» 인가 — 화면이 그렇다고 알려 줘야 한다 */
  function 맛보기인가(코드) {
    return !!뿌리["SCHOOLS_" + 코드 + "_MEATBOGI"];
  }

  /**
   * 학교 이름으로 찾기.
   * 「거제중」 처럼 줄여 쳐도 찾히게 «들어 있으면» 으로 본다.
   * @return [{ 이름, 시군구, 급별 }]
   */
  function 학교찾기(목록, 글, 몇개) {
    if (!목록 || !글) return [];
    var 찾을것 = String(글).replace(/\s+/g, "");
    if (찾을것.length < 2) return [];
    var 나온다 = [];
    for (var i = 0; i < 목록.length && 나온다.length < (몇개 || 20); i++) {
      var 이름 = 목록[i][1] || "";
      if (이름.replace(/\s+/g, "").indexOf(찾을것) >= 0) {
        나온다.push({ 이름: 이름, 시군구: 목록[i][2] || "", 급별: 목록[i][3] || "" });
      }
    }
    return 나온다;
  }

  /* ── 시군구 → 관측지점 ─────────────────────────────────── */
  /**
   * @return { 지점, 어떻게, 고를것 }
   *   어떻게 : "이름이같다" | "골라야한다" | "없다"
   *
   * 🔴 «골라야한다» 를 «저절로 골랐다» 로 바꾸지 말 것.
   *    위경도가 없는 지금은 어느 지점이 가까운지 알 방법이 정말로 없다.
   *    엉뚱한 지점을 조용히 골라 주면 그 통계로 행사 날짜를 정하게 된다.
   */
  /**
   * 격자표(data/격자.js)에서 시군구 한 곳의 자리를 찾는다. 없으면 null.
   *
   * 🚨 «창원시» 가 안 맞는 문제
   *    기상청 격자표는 창원시를 **다섯 구로 쪼개** 담고 있다 :
   *      창원시마산합포구 · 창원시마산회원구 · 창원시성산구 · 창원시의창구 · 창원시진해구
   *    그런데 학교 목록의 시군구는 도로명주소에서 뽑은 **«창원시»** 다.
   *    딱 맞는 이름으로만 찾으면 **창원 지역 학교가 통째로 안 잡힌다**(오류는 안 난다).
   *    수원시·성남시·고양시·용인시·청주시·천안시·전주시·포항시도 같은 꼴이다.
   *
   *    👉 딱 맞는 것이 없으면 **그 이름으로 시작하는 것들**을 모아 가운데를 잡는다.
   *    ⚠ 다섯 구의 한가운데라 어느 구와도 몇 km 어긋난다 — 어차피 «어느 관측소를
   *      볼까» 를 정하는 데 쓰는 값이라 그것으로 넉넉하다.
   */
  function 시군구자리(시도, 시군구) {
    var 표 = 뿌리.격자표;
    if (!표 || !표.것들 || !시군구) return null;
    var i, s;

    // ㉮ 이름이 딱 맞는 것
    for (i = 0; i < 표.것들.length; i++) {
      s = 표.것들[i];
      if (s.시도 === 시도 && s.시군구 === 시군구) return s;
    }

    // ㉯ 그 이름으로 «시작하는» 것들 (창원시 → 창원시○○구)
    var 모음 = [];
    for (i = 0; i < 표.것들.length; i++) {
      s = 표.것들[i];
      if (s.시도 === 시도 && s.시군구.indexOf(시군구) === 0) 모음.push(s);
    }

    // ㉰ 🚨 광역시·특별시는 시군구가 «구» 로만 들어 있다.
    //    격자표에는 「종로구·중구…」 만 있는데 관측소의 시군구는 「서울」 이라
    //    ㉮㉯ 둘 다 못 찾고 **예보가 통째로 안 나왔다**(실제로 겪었다).
    //    그런 경우에는 그 시·도 전체의 가운데를 쓴다 — 「서울」 은 곧 서울시이므로 뜻이 통한다.
    //    ⚠ 아무 때나 이러면 안 된다. **묻는 이름이 시·도 이름과 같을 때만** 이다
    //      (경상남도에 없는 시군구를 물었다고 «경남 한가운데» 를 주면 엉뚱하다).
    if (!모음.length) {
      var 민시도 = String(시도).replace(/(특별시|광역시|특별자치시|특별자치도|도)$/, "");
      if (시군구 === 민시도 || 시군구 === 시도) {
        for (i = 0; i < 표.것들.length; i++) {
          if (표.것들[i].시도 === 시도) 모음.push(표.것들[i]);
        }
      }
    }

    if (!모음.length) return null;
    if (모음.length === 1) return 모음[0];

    var 위 = 0, 경 = 0;
    for (i = 0; i < 모음.length; i++) { 위 += 모음[i].위도; 경 += 모음[i].경도; }
    위 /= 모음.length; 경 /= 모음.length;
    return {
      시도: 시도, 시군구: 시군구, 위도: 위, 경도: 경,
      nx: null, ny: null,               // 격자는 구마다 달라 뭉뚱그리지 않는다
      쪼개진것: 모음.length              // 화면이 «여러 구를 아우른 값» 이라 말할 수 있게
    };
  }

  function 시군구로(지점목록, 시도, 시군구) {
    var 그동네 = (지점목록 || []).filter(function (s) { return s.시도 === 시도; });

    // ㉮ 시군구 이름이 그대로 지점 이름인 곳 (거제시 → 거제)
    var 민이름 = String(시군구 || "").replace(/(시|군|구)$/, "");
    var 딱 = 그동네.filter(function (s) {
      return s.시군구 === 시군구 || s.이름 === 민이름 || s.이름 === 시군구;
    });
    if (딱.length === 1) return { 지점: 딱[0], 어떻게: "이름이같다", 고를것: 그동네 };

    // ㉯ 격자표가 있으면 «거리» 로 고른다.
    //
    //    🔴 지점의 위경도가 아니라 **그 지점이 있는 시군구의 가운데**끼리 잰다.
    //       지점의 진짜 좌표는 아직 없기 때문이다. 우리가 묻는 것은 결국
    //       「어느 관측소가 가까운가」 가 아니라 「어느 동네의 관측소를 볼까」 라서
    //       이것으로 뜻이 통한다. 다만 **몇 km 어긋난다** — 화면에 그렇게 적는다.
    var 여기 = 시군구자리(시도, 시군구);
    if (여기) {
      var 잰것 = [];
      // 같은 시·도를 먼저 보되, 없으면 온 나라에서 찾는다(도 경계에 붙은 학교)
      [그동네, 지점목록 || []].forEach(function (무리) {
        if (잰것.length) return;
        무리.forEach(function (s) {
          var 저기 = 시군구자리(s.시도, s.시군구);
          if (!저기) return;
          var d = 거리(여기.위도, 여기.경도, 저기.위도, 저기.경도);
          if (d != null) 잰것.push({ 지점: s, 거리: d });
        });
      });
      if (잰것.length) {
        잰것.sort(function (a, b) { return a.거리 - b.거리; });
        return {
          지점: 잰것[0].지점, 어떻게: "거리로골랐다",
          거리: 잰것[0].거리, 고를것: 그동네,
          가까운것들: 잰것.slice(0, 3)
        };
      }
    }

    // ㉰ 같은 시군구에 관측소가 «여럿» 인데 격자표가 없다 (창원 + 북창원)
    if (딱.length > 1) {
      return { 지점: null, 어떻게: "여럿이다", 고를것: 딱 };
    }

    if (!그동네.length) return { 지점: null, 어떻게: "없다", 고를것: [] };
    return { 지점: null, 어떻게: "골라야한다", 고를것: 그동네 };
  }

  /**
   * 두 곳 사이 거리(km) — 위경도가 둘 다 있을 때만 쓴다.
   * 지금은 쓰이지 않지만, 진짜 지점 목록이 들어오면 `시군구로()` 가 이걸 쓴다.
   */
  function 거리(위1, 경1, 위2, 경2) {
    if (위1 == null || 경1 == null || 위2 == null || 경2 == null) return null;
    var R = 6371, 라 = Math.PI / 180;
    var d위 = (위2 - 위1) * 라, d경 = (경2 - 경1) * 라;
    var a = Math.sin(d위 / 2) * Math.sin(d위 / 2) +
            Math.cos(위1 * 라) * Math.cos(위2 * 라) * Math.sin(d경 / 2) * Math.sin(d경 / 2);
    return R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  }

  /** 위경도가 있는 지점들 가운데 가장 가까운 곳 */
  function 가까운곳(지점목록, 위도, 경도) {
    var 가장 = null, 가장멀기 = Infinity;
    (지점목록 || []).forEach(function (s) {
      var d = 거리(위도, 경도, s.위도, s.경도);
      if (d != null && d < 가장멀기) { 가장멀기 = d; 가장 = s; }
    });
    return 가장 ? { 지점: 가장, 거리: 가장멀기 } : null;
  }

  뿌리.Place = {
    교육청: 교육청, 시도코드: 시도코드,
    시도들: 시도들, 그시도지점: 그시도지점,
    학교부르기: 학교부르기, 학교찾기: 학교찾기, 맛보기인가: 맛보기인가,
    시군구로: 시군구로, 거리: 거리, 가까운곳: 가까운곳, 시군구자리: 시군구자리
  };
})(typeof window !== "undefined" ? window : globalThis);
